// Turns the recorded spike runs into a TypeScript fixture the engine tests replay.
// usage: node .spike/make-fixtures.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const runsDir = new URL("./runs/", import.meta.url).pathname;
const outFile = join(process.cwd(), "tests/fixtures/runs.ts");

const labels = {
  "A-longtext": "answer-heavy (first run, no wall clock recorded)",
  "A2-longtext": "answer-heavy",
  "B-thinking": "thinking-heavy, very short",
  "C-toolstall": "tool-heavy with an 8s stall",
  "D-thinklong": "thinking-heavy",
  "E-multistep": "tool-heavy, 4 shell calls",
};

function summarise(rows, name) {
  const wall = rows.find((r) => r.wall)?.wall ?? null;
  const startedAts = rows
    .map((r) => (r.activeTurn?.startedAt ? Date.parse(r.activeTurn.startedAt) : null))
    .filter((v) => v !== null);
  const turnStart = startedAts.length ? Math.min(...startedAts) - wall : rows.find((r) => r.ev === "turn_started").t;
  const end = rows.find((r) => ["turn_completed", "turn_failed", "turn_canceled"].includes(r.ev));
  const deltas = rows.filter((r) => r.ev === "delta").map((r) => [Math.round(r.t - turnStart), r.kind === "t" ? "thinking" : "answer", r.chars]);
  // Only runs recorded after the recorder started capturing callId can be replayed: without it a
  // "completed" cannot be matched to its "running", and the generation clock would never resume.
  const tools = rows
    .filter((r) => r.ev === "item" && r.kind === "tool_call" && r.status && typeof r.callId === "string")
    .map((r) => [Math.round(r.t - turnStart), String(r.callId), r.status]);
  const samples = rows
    .filter((r) => r.usage?.outputTokens !== undefined)
    .map((r) => [Math.round(r.t - turnStart), r.usage.outputTokens]);
  const baseline = samples.find(([t]) => t >= 0)?.[1] ?? samples[0][1];
  const finalTokens = end?.usage?.outputTokens ?? samples[samples.length - 1][1];
  return {
    label: labels[name] ?? name,
    turnStartMs: 0,
    turnEndMs: Math.round(end.t - turnStart),
    baselineTokens: baseline,
    finalTokens,
    deltas,
    // tool call start/finish events: generation time stops while one runs
    tools,
    // samples that fall inside the turn, in absolute provider-token space
    samples: samples.filter(([t]) => t >= 0),
  };
}

const files = readdirSync(runsDir).filter((f) => f.endsWith(".jsonl"));
const runs = {};
for (const file of files) {
  const rows = readFileSync(join(runsDir, file), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  const name = file.replace(".jsonl", "");
  if (!rows.some((r) => r.wall)) continue; // pre-fix run without a wall clock cannot be replayed reliably
  runs[name.replace(/[^a-zA-Z0-9]/g, "_").replace(/^_/, "")] = summarise(rows, name);
}

const body = `// GENERATED by .spike/make-fixtures.mjs from the phase 1 spike runs. Do not edit by hand.
// Real recorded turns on pi/deepseek/deepseek-flash, used to assert the engine against actual
// cadences instead of invented ones. Times are milliseconds from turn start.

export type RecordedDelta = [tMs: number, kind: "thinking" | "answer", chars: number];

export type RecordedToolEvent = [tMs: number, callId: string, status: string];

export interface RecordedRun {
  label: string;
  turnEndMs: number;
  baselineTokens: number;
  finalTokens: number;
  deltas: RecordedDelta[];
  tools: RecordedToolEvent[];
  /** [tMs, absolute provider output tokens] */
  samples: [number, number][];
}

export const RECORDED_RUNS: Record<string, RecordedRun> = ${JSON.stringify(runs, null, 2)} as Record<string, RecordedRun>;
`;
writeFileSync(outFile, body);
console.log(`wrote ${outFile} with ${Object.keys(runs).length} runs`);
for (const [name, run] of Object.entries(runs)) {
  const chars = run.deltas.reduce((s, d) => s + d[2], 0);
  const tokens = run.finalTokens - run.baselineTokens;
  console.log(
    `  ${name.padEnd(14)} ${run.deltas.length} deltas, ${chars} chars, ${tokens} tokens, ${(run.turnEndMs / 1000).toFixed(1)}s, ${(chars / tokens).toFixed(2)} chars/token`,
  );
}
